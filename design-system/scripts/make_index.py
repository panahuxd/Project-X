"""Generate components/INDEX.md: one table of every DKB component with what it is for.
Reads components.json (variants, properties) and the Purpose section of each spec.
Run after any component change:  python3 design-system/scripts/make_index.py"""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
man = json.load(open(os.path.join(ROOT, 'components.json')))['components']

GROUPS = [
    ('Actions', ['button', 'icon-button', 'button-group', 'toggle', 'toggle-group']),
    ('Forms', ['field', 'label', 'input', 'textarea', 'input-group', 'input-otp', 'select', 'native-select', 'combobox', 'checkbox', 'radio', 'switch', 'slider', 'calendar', 'date-picker']),
    ('Feedback and status', ['alert', 'badge', 'toast', 'progress', 'spinner', 'skeleton', 'empty', 'tooltip']),
    ('Overlays and menus', ['dialog', 'alert-dialog', 'sheet', 'drawer', 'popover', 'hover-card', 'dropdown-menu', 'context-menu', 'menubar', 'command']),
    ('Content and data', ['card', 'item', 'table', 'data-table', 'tabs', 'accordion', 'collapsible', 'avatar', 'kbd', 'separator', 'scroll-area', 'resizable', 'chart']),
    ('Navigation', ['navigation-menu', 'breadcrumb', 'pagination', 'carousel', 'sidebar']),
    ('Building blocks (used inside other components)', ['menu-item', 'tab', 'accordion-item', 'table-cell', 'pagination-link', 'navigation-menu-trigger', 'navigation-menu-link', 'sidebar-menu-button', 'calendar-day', 'chart-legend', 'chart-tooltip', 'slot', 'overlay', 'template-region']),
    ('Commerce: page shell (DKB Commerce)', ['header', 'mobile-header', 'footer', 'bottom-nav', 'action-bar', 'account-menu', 'logo', 'bottom-nav-item']),
    ('Layout templates (DKB Commerce; start every screen from one; patterns/layouts.md)', ['template/home', 'template/listing', 'template/detail', 'template/checkout', 'template/account', 'template/form', 'template/workspace', 'template/content', 'template/result', 'template/auth']),
]

TEMPLATE_PURPOSE = {
    'template-region': 'Placeholder region inside a layout template; replace every one with real content.',
    'template/home': 'T1 Home and landing pages: optional full-bleed hero, hero row 3·6·3, stacked sections.',
    'template/listing': 'T2 Product lists and search results: filters 3 cols beside results 9 cols, sticky sort bar.',
    'template/detail': 'T3 Product and bundle pages: gallery 3 · info 5 · sticky buy box 4.',
    'template/checkout': 'T4 Cart, shipping, payment and repayment steps: focused shell, cards 8 cols beside a sticky bill box.',
    'template/account': 'T5 Profile pages: side nav 3 cols beside content 9 cols.',
    'template/form': 'T6 Forms and tasks (RFQ, KYC, onboarding, credit request): form 8 cols, optional summary 4 cols.',
    'template/workspace': 'T7 Admin and report pages (B2E company admin, portal admin): sidebar on the right, KPI cards, chart, data table.',
    'template/content': 'T8 Terms, privacy, help and FAQ: reading column 720 with an optional table of contents.',
    'template/result': 'T9 Thank-you, payment result, 404 and access gates: centred 480 block.',
    'template/auth': 'T10 Login, OTP and sign-up: centred 384 card.',
}

def purpose(name):
    if name in TEMPLATE_PURPOSE: return TEMPLATE_PURPOSE[name]
    if name == 'bottom-nav-item': return 'One destination (icon + label) inside bottom-nav.'
    p = os.path.join(ROOT, 'components', name + '.md')
    if not os.path.exists(p): return ''
    s = open(p).read()
    m = re.search(r'## Purpose\n(.+?)(?:\n\n|\n##)', s, re.S)
    if not m:  # stub spec: first sentence after the title
        m = re.search(r'^# .+?\n\n(.+?)(?:\n|$)', s, re.S)
    text = m.group(1).strip().replace('\n', ' ') if m else ''
    safe = text.replace('e.g.', 'e\u2024g\u2024').replace('i.e.', 'i\u2024e\u2024')
    first = re.split(r'(?<=[.!?])\s', safe)[0].replace('\u2024', '.')
    return first.replace('|', '\\|')

def variants(c):
    return '; '.join(f"{k}: {'/'.join(v)}" for k, v in c['variants'].items())

listed = [n for _, ns in GROUPS for n in ns]
missing = sorted(set(man) - set(listed))
unknown = sorted(set(listed) - set(man))
if unknown: raise SystemExit(f'INDEX groups name unknown components: {unknown}')
if missing: GROUPS.append(('Other', missing))

out = ['# Component index', '',
       'Generated by `scripts/make_index.py` from `components.json` and the specs. Do not edit by hand.',
       'Pick a component here, then read its spec. Keys, property ids and the library file (`components` = DKB Components, `commerce` = DKB Commerce) are in `../components.json`.', '']
for title, names in GROUPS:
    out += [f'## {title}', '', '| Component | Use it for | Variants | Spec |', '|---|---|---|---|']
    for n in names:
        c = man[n]
        spec = c.get('spec', f'components/{n}.md')
        link = f'[{n}.md]({n}.md)' if spec == f'components/{n}.md' else (f'[{os.path.basename(spec)}]({os.path.basename(spec)})' if spec.startswith('components/') else f'[layouts.md](../{spec})')
        out.append(f'| `{n}` | {purpose(n)} | {variants(c)} | {link} |')
    out.append('')
out += ['## Written guides (no Figma component)', '', '| Guide | What it covers |', '|---|---|',
        '| [aspect-ratio.md](aspect-ratio.md) | Media ratios for product images, banners, video |',
        '| [direction.md](direction.md) | RTL rules: what mirrors, LTR islands, digits |',
        '| [typography.md](typography.md) | shadcn typography examples mapped to the 15 DKB text styles |', '']
out += ['## Icons', '', 'The full Lucide set (1,867) is in DKB Components: [ICONS.md](ICONS.md) lists every icon with its search tags; keys are in `../components.json` → `icons`.', '']
open(os.path.join(ROOT, 'components', 'INDEX.md'), 'w').write('\n'.join(out))
print(f'INDEX.md: {len(man)} components')

# ICONS.md: every icon with its tags, for finding one by meaning (grep a tag, e.g. "delivery")
icons = json.load(open(os.path.join(ROOT, 'components.json')))['icons']
common = sorted(n for n, i in icons.items() if i.get('common'))
ic = ['# Icon index', '',
      'Generated by `scripts/make_index.py` from `components.json`. Do not edit by hand.',
      f'{len(icons)} icons: all {len(icons) - 1} of Lucide 1.52.0 plus `trash-2` (kept from the first icon set), as components `icon/<name>` in DKB Components (page Icons).',
      'Each is 24×24, stroke 2, the glyph stroke bound to `text/default`; place at `icon/size/*` and recolour the glyph stroke with a text token.',
      'Find an icon by name or tag here, then take its key from `../components.json` → `icons` (one line per icon).',
      'Names describe the drawing, not the meaning: in RTL, "back" is `arrow-right` / `chevron-right` (see [direction.md](direction.md)).', '',
      f'## Common ({len(common)}) — built into agent-helpers.js', '', ', '.join(f'`{n}`' for n in common), '',
      '## All icons', '', '| Icon | Tags |', '|---|---|']
ic += [f"| `{n}` | {', '.join(i.get('tags', []))} |" for n, i in sorted(icons.items())]
open(os.path.join(ROOT, 'components', 'ICONS.md'), 'w').write('\n'.join(ic) + '\n')
print(f'ICONS.md: {len(icons)} icons, {len(common)} common')
