"""Generate scripts/figma/agent-helpers.js: a prelude for use_figma scripts in design files,
with every published library key built in (tokens, text and effect styles, components, icons).
Run after figma-library-keys.json or components.json changes:  python3 design-system/scripts/make_agent_helpers.py"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
lib = json.load(open(os.path.join(ROOT, 'figma-library-keys.json')))
man = json.load(open(os.path.join(ROOT, 'components.json')))
keys = {
    'tokens': lib['variables'],
    'styles': {**lib['textStyles'], **lib['effectStyles']},
    'components': {n: c['key'] for n, c in man['components'].items()},
    'icons': {n: i['key'] for n, i in man['icons'].items()},
}
JS = r'''// DKB agent helpers — GENERATED by design-system/scripts/make_agent_helpers.py. Do not edit by hand.
// Paste this whole file at the top of a use_figma script that designs in a file using the DKB libraries.
// 1) await use({ tokens: [...], styles: [...], components: [...], icons: [...] })  imports only what you name (by key)
// 2) paint / bind / text / instance / icon / setModes  build with tokens and library components
// Names are the same as in token-reference.md (with "/"), components/INDEX.md and components.json.
const KEYS = __KEYS__;
const V = {}, S = {}, C = {}, I = {};
async function use({ tokens = [], styles = [], components = [], icons = [] } = {}) {
  const need = (map, n, kind) => { const k = KEYS[kind][n]; if (!k) throw new Error(`Unknown ${kind.slice(0, -1)} "${n}"`); return k; };
  for (const n of tokens) if (!V[n]) V[n] = await figma.variables.importVariableByKeyAsync(need(V, n, 'tokens'));
  for (const n of styles) if (!S[n]) S[n] = await figma.importStyleByKeyAsync(need(S, n, 'styles'));
  for (const n of components) if (!C[n]) C[n] = await figma.importComponentSetByKeyAsync(need(C, n, 'components'));
  for (const n of icons) if (!I[n]) I[n] = await figma.importComponentByKeyAsync(need(I, n, 'icons'));
}
for (const st of ['Regular', 'Medium', 'SemiBold', 'Bold']) await figma.loadFontAsync({ family: 'Digikala', style: st });

// Fill or stroke bound to a token: node.fills = paint('bg/default'); node.strokes = paint('border/default')
const paint = (n, opacity) => { const p = figma.variables.setBoundVariableForPaint({ type: 'SOLID', color: { r: 0.5, g: 0.5, b: 0.5 } }, 'color', V[n]); return [opacity == null ? p : Object.assign({}, p, { opacity })]; };

// Bind numbers to tokens: bind(frame, { padding: 'space/16', itemSpacing: 'space/8', radius: 'radius/card', strokeWeight: 'border-width/default' })
// Shorthands: padding, paddingX, paddingY, radius, strokeWeight.
const SHORT = { padding: ['paddingTop', 'paddingRight', 'paddingBottom', 'paddingLeft'], paddingX: ['paddingLeft', 'paddingRight'], paddingY: ['paddingTop', 'paddingBottom'],
  radius: ['topLeftRadius', 'topRightRadius', 'bottomLeftRadius', 'bottomRightRadius'], strokeWeight: ['strokeTopWeight', 'strokeRightWeight', 'strokeBottomWeight', 'strokeLeftWeight'] };
const bind = (node, map) => { for (const [prop, tok] of Object.entries(map)) for (const p of SHORT[prop] || [prop]) node.setBoundVariable(p, V[tok]); return node; };

// Styled text, right-aligned: await text(parent, 'متن', 'body', 'text/default')
async function text(parent, chars, style, color = 'text/default', align = 'RIGHT') {
  const t = figma.createText(); await t.setTextStyleIdAsync(S[style].id); t.characters = chars; t.fills = paint(color); t.textAlignHorizontal = align;
  if (parent) parent.appendChild(t); return t;
}

// Library instance by variant + properties by name (variant props too):
// instance('button', { variant: 'primary', size: 'md', state: 'default' }, { label: 'ثبت سفارش', showIconStart: true, iconStart: I['shopping-cart'].id })
function instance(name, variant = {}, props = {}) {
  const set = C[name]; if (!set) throw new Error(`Component "${name}" not loaded: add it to use({ components })`);
  const v = Object.keys(variant).length ? set.children.find(c => Object.entries(variant).every(([k, val]) => c.name.split(', ').includes(`${k}=${val}`))) : set.defaultVariant;
  if (!v) throw new Error(`No ${name} variant ${JSON.stringify(variant)}`);
  const i = v.createInstance(); setProps(i, props); return i;
}
function setProps(inst, props) {
  const map = {};
  for (const [k, val] of Object.entries(props)) { const id = Object.keys(inst.componentProperties).find(x => x === k || x.startsWith(k + '#')); if (!id) throw new Error(`${inst.name} has no property ${k}`); map[id] = val; }
  if (Object.keys(map).length) inst.setProperties(map); return inst;
}
// Nested exposed instance (e.g. the label inside field): setProps(child(fieldInstance, 'label'), { text: 'شماره موبایل' })
const child = (inst, name) => inst.findOne(n => n.type === 'INSTANCE' && n.name === name);

// RTL layout helpers. Figma auto layout runs left to right, so:
// vstack aligns children to the right (start); hrow takes children in READING order (right to left) and appends them reversed.
// const col = vstack('section', { itemSpacing: 'space/16', padding: 'space/24' });  const r = hrow('actions', [primaryBtn, secondaryBtn], { itemSpacing: 'space/8' });
function vstack(name, tokens = {}) { const f = figma.createAutoLayout('VERTICAL', { name }); f.fills = []; f.counterAxisAlignItems = 'MAX'; return bind(f, tokens); }
function hrow(name, childrenInReadingOrder = [], tokens = {}) { const f = figma.createAutoLayout('HORIZONTAL', { name }); f.fills = []; f.counterAxisAlignItems = 'CENTER'; f.primaryAxisAlignItems = 'MAX'; for (const c of [...childrenInReadingOrder].reverse()) f.appendChild(c); return bind(f, tokens); }

// Icon instance sized and coloured by tokens: icon('search', 'icon/size/md', 'text/muted')
function icon(name, size = 'icon/size/md', color = 'text/default') {
  const i = I[name].createInstance(); i.setBoundVariable('width', V[size]); i.setBoundVariable('height', V[size]); i.children[0].strokes = paint(color); return i;
}

// Brand and screen modes on a screen frame: await setModes(frame, 'B2E', 'Mobile')
async function setModes(frame, brand, screen) {
  await use({ tokens: ['bg/primary', 'control/height-md'] });
  const brandVar = await figma.variables.getVariableByIdAsync(Object.values(V['bg/primary'].valuesByMode)[0].id);
  const brandCol = await figma.variables.getVariableCollectionByIdAsync(brandVar.variableCollectionId);
  const respCol = await figma.variables.getVariableCollectionByIdAsync(V['control/height-md'].variableCollectionId);
  frame.setExplicitVariableModeForCollection(brandCol, brandCol.modes.find(m => m.name === brand).modeId);
  frame.setExplicitVariableModeForCollection(respCol, respCol.modes.find(m => m.name === screen).modeId);
}
// Layout templates (patterns/layouts.md). Start every screen from one:
// const f = await startFromTemplate('template/checkout', 'mobile', 'B2E', 'checkout/payment/mobile');
// It places the template, detaches it (templates are the ONE thing you detach), names the frame and sets brand + screen modes.
async function startFromTemplate(name, screen, brand, frameName, parent = figma.currentPage) {
  await use({ components: [name] });
  const v = C[name].children.find(c => c.name === `screen=${screen}`); if (!v) throw new Error(`${name} has no screen=${screen}`);
  const inst = v.createInstance(); parent.appendChild(inst);
  const frame = inst.detachInstance(); frame.name = frameName;
  await setModes(frame, brand, screen === 'desktop' ? 'Desktop' : 'Mobile');
  return frame;
}
// The regions still to fill, by name: const r = await regions(f); r.filters, r['bill-box'] …
async function regions(frame) {
  const o = {};
  for (const n of frame.findAllWithCriteria({ types: ['INSTANCE'] })) { const m = await n.getMainComponentAsync(); if (m && m.parent && m.parent.name === 'template-region') o[n.name] = n; }
  return o;
}
// Put real content where a region is: same place and width behaviour (FILL stays FILL, a fixed region keeps its width); the region is removed.
function fillRegion(region, node) {
  const p = region.parent; p.insertChild(p.children.indexOf(region), node);
  if (region.layoutSizingHorizontal === 'FILL') node.layoutSizingHorizontal = 'FILL';
  else { const hug = 'layoutMode' in node && node.layoutMode !== 'NONE'; node.resize(region.width, node.height); if (hug) node.layoutSizingVertical = 'HUG'; }
  region.remove(); return node;
}
// ---- end of DKB agent helpers ----
'''
out = JS.replace('__KEYS__', json.dumps(keys, ensure_ascii=False, separators=(',', ':')))
path = os.path.join(ROOT, 'scripts', 'figma', 'agent-helpers.js')
open(path, 'w').write(out)
print(f'agent-helpers.js: {len(out)} chars, {len(keys["tokens"])} tokens, {len(keys["styles"])} styles, {len(keys["components"])} components, {len(keys["icons"])} icons')
